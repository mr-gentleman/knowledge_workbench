-- 002 — Knowledge Workbench grants. Run as ACCOUNTADMIN (owns AI_PLATFORM + its schemas).
--
-- Modeled on live grants for AI_PLATFORM.DICTIONARY / CORPUS (checked 2026-10-01).
-- One deliberate difference: NOBODY but the app's role can write here. DATAENG has
-- INSERT/UPDATE on DICTIONARY and TASK_MANAGER runs the Sheets reload there — neither
-- gets write on WORKBENCH. No DELETE for anyone: rows are retired, never removed.
-- Schema-level future grants take precedence over database-level ones.

-- ── App role: the ONLY writer ─────────────────────────────────────────────
-- Owns the Streamlit app; SiS runs with the owner's rights, so this role's grants
-- = the app's grants. Must have NO write on AI_PLATFORM.DICTIONARY (isolation invariant).
CREATE ROLE IF NOT EXISTS WORKBENCH_APP;
GRANT ROLE WORKBENCH_APP TO ROLE ACCOUNTADMIN;
-- GRANT ROLE WORKBENCH_APP TO USER <you>;          -- to deploy/own the app
GRANT USAGE ON DATABASE AI_PLATFORM                      TO ROLE WORKBENCH_APP;
GRANT USAGE ON SCHEMA   AI_PLATFORM.WORKBENCH            TO ROLE WORKBENCH_APP;
GRANT CREATE STREAMLIT, CREATE STAGE ON SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT SELECT, INSERT, UPDATE ON ALL    TABLES    IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES    IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT SELECT                 ON ALL    VIEWS     IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT SELECT                 ON FUTURE VIEWS     IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT USAGE                  ON ALL    SEQUENCES IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
GRANT USAGE                  ON FUTURE SEQUENCES IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE WORKBENCH_APP;
-- Read the legacy fact tables (PI → fact_table_core check during import) — read only:
GRANT USAGE  ON SCHEMA AI_PLATFORM.DICTIONARY                     TO ROLE WORKBENCH_APP;
GRANT SELECT ON ALL    TABLES IN SCHEMA AI_PLATFORM.DICTIONARY    TO ROLE WORKBENCH_APP;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AI_PLATFORM.DICTIONARY    TO ROLE WORKBENCH_APP;  -- DICTIONARY tables are rebuilt (CREATE OR REPLACE); ALL alone would be lost
-- TODO: warehouse for the app, and read access to AC.* for SQL validation (via the
-- read-only safe-execution path, not direct grants) — decide with the validator.
GRANT USAGE ON WAREHOUSE BIZ_AI_WH TO ROLE WORKBENCH_APP;

-- ── CoCo (Cortex Code): builds objects, reads everything — same as DICTIONARY/CORPUS
GRANT USAGE ON SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;
GRANT CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE FUNCTION
      ON SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;
GRANT SELECT ON ALL    TABLES IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;
GRANT SELECT ON ALL    VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH TO ROLE CORTEX_CODE_ROLE;

-- ── Readers: same read set as DICTIONARY ───────────────────────────────────
-- DATAENG (team), DATAENG_RO (read-only), GLEAN_QUERY_SNOWFLAKE_ROLE (your default
-- role + the Oracle's caller role — needed once the agent reads the served view).
GRANT USAGE  ON SCHEMA AI_PLATFORM.WORKBENCH                    TO ROLE DATAENG;
GRANT SELECT ON ALL    TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG;
GRANT SELECT ON ALL    VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG;

GRANT USAGE  ON SCHEMA AI_PLATFORM.WORKBENCH                    TO ROLE DATAENG_RO;
GRANT SELECT ON ALL    TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG_RO;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG_RO;
GRANT SELECT ON ALL    VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG_RO;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE DATAENG_RO;

GRANT USAGE  ON SCHEMA AI_PLATFORM.WORKBENCH                    TO ROLE GLEAN_QUERY_SNOWFLAKE_ROLE;
GRANT SELECT ON ALL    TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE GLEAN_QUERY_SNOWFLAKE_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE GLEAN_QUERY_SNOWFLAKE_ROLE;
GRANT SELECT ON ALL    VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE GLEAN_QUERY_SNOWFLAKE_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA AI_PLATFORM.WORKBENCH   TO ROLE GLEAN_QUERY_SNOWFLAKE_ROLE;

