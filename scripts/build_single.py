"""Generate the pasteable Snowflake app from the authoritative modular source."""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = ('app/db.py', 'app/repositories.py', 'app/services.py', 'streamlit_app.py')


def build():
    chunks = ['"""Generated by scripts/build_single.py; edit the modular source."""\n']
    for path in PARTS:
        source = (ROOT / path).read_text()
        tree = ast.parse(source)
        lines = source.splitlines(keepends=True)
        # Only local imports disappear; external imports stay with their section.
        for node in reversed(tree.body):
            if isinstance(node, ast.ImportFrom) and (node.module or '').split('.')[0] == 'app':
                del lines[node.lineno - 1:node.end_lineno]
        source = ''.join(lines).replace('repo.', '').replace('services.', '')
        chunks.append(f'\n# Source: {path}\n' + source)
    return '\n'.join(chunks)


if __name__ == '__main__':
    (ROOT / 'streamlit_app_single.py').write_text(build())
